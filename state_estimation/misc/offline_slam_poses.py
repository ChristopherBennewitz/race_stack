#!/usr/bin/env python3
"""Re-runs Cartographer offline on a bag's lidar scans, for a SLAM pose that does not depend on the live estimator.

The pose in a recorded take (`/car_state/pose`) was computed from the live estimator's odometry, so it is not
independent evidence for the global filter: its innovations look too good, and the pose delay and noise fitted to it
are biased. Here Cartographer sees only `/scan` and the static lidar mounting (`/tf_static`), with **no odometry and
no IMU**, so its pose comes from scan matching alone. The poses go to `<out-dir>/<bag name>.csv` (`t x y yaw`, the
`/tracked_pose` stamps, i.e. scan time) which `ekf_replay.py --global --pose-dir` reads.

What this is and is not:
- Mapping mode (the default) builds a map from the take itself, so the poses are in that map's frame, which starts at
  the first pose. The global filter only needs the poses to be consistent with each other. Give `--map` a `.pbstream`
  of the track to localize in it instead, as the car does (frame then matches the live `map`).
- The pose is the online `/tracked_pose` (what a live system would have had at that moment), not the final optimized
  trajectory, so loop-closure jumps are in it.
- Its stamp is scan time, and the stamp-to-content delay it implies belongs to the *scan matcher alone*. The live pose
  is `map->odom` composed with the local filter's pose at the stamp, whose odometry part is exact at the stamp, so
  the live delay is expected to be smaller than what this pose gives.

Run it where ROS 2 Humble and `cartographer_ros` are sourced (the race_stack container). It uses a private DDS domain
and FastDDS so it does not touch a running stack (the container's default is zenoh, which needs a router):

    python3 state_estimation/misc/offline_slam_poses.py sysid_bags/sysid_* --out-dir sysid_poses
    f1tenth_parallel_sim/.venv/bin/python state_estimation/misc/ekf_replay.py sysid_bags/sysid_<take> \\
        --global --pose-dir sysid_poses --estimate-delay

``--dry-run`` prints the commands and the derived Cartographer configuration without starting anything.
"""

from __future__ import annotations

import argparse
import math
import os
import shutil
import signal
import subprocess
import sys
import tempfile
import time
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIG_ROOT = REPO / 'stack_master' / 'config'
POSE_TOPIC = '/tracked_pose'
REPLAY_TOPICS = ('/scan', '/tf_static')  # everything else in the take comes from the live estimator


# --- Cartographer configuration -------------------------------------------------------------------------------------

def derive_config(config_root, racecar_version, work_dir, localization=False):
    """Writes a copy of the car's SLAM configuration with the odometry prior removed.

    The car's files include the shared ones by a relative path (``../../slam/base.lua``), so the directory layout is
    kept. Returns ``(configuration_directory, configuration_basename)``.
    """
    config_root = Path(config_root)
    car_slam = config_root / racecar_version / 'slam'
    shared = config_root / 'slam'
    for source in (car_slam, shared):
        if not source.is_dir():
            raise FileNotFoundError(f'no SLAM configuration at {source}')
    work_dir = Path(work_dir)
    shutil.copytree(shared, work_dir / 'slam', dirs_exist_ok=True)
    car_copy = work_dir / racecar_version / 'slam'
    shutil.copytree(car_slam, car_copy, dirs_exist_ok=True)
    base = 'f110_2d_loc.lua' if localization else 'f110_2d.lua'
    (car_copy / 'offline_2d.lua').write_text(
        f'-- Generated by offline_slam_poses.py: the car\'s {base} without any odometry prior.\n'
        f'include "{base}"\n\n'
        'options.use_odometry = false\n'
        'options.provide_odom_frame = false\n'
        'options.published_frame = "base_link"\n'
        'options.publish_to_tf = false\n'
        'options.publish_tracked_pose = true\n\n'
        'return options\n')
    return car_copy, 'offline_2d.lua'


# --- processes ------------------------------------------------------------------------------------------------------

def environment(domain_id, rmw):
    """A private DDS domain on the loopback, so the run cannot talk to (or be disturbed by) a live stack."""
    env = dict(os.environ)
    env.update({'ROS_DOMAIN_ID': str(domain_id), 'ROS_LOCALHOST_ONLY': '1', 'RMW_IMPLEMENTATION': rmw})
    return env


def commands(bag, config_dir, basename, out_csv, pbstream=None, rate=1.0):
    """The three processes of one run: Cartographer, the pose recorder and the bag player."""
    cartographer = ['ros2', 'run', 'cartographer_ros', 'cartographer_node',
                    '-configuration_directory', str(config_dir), '-configuration_basename', basename]
    if pbstream:
        cartographer += ['-load_state_filename', str(pbstream)]
    cartographer += ['--minloglevel', '2', '--ros-args', '-p', 'use_sim_time:=true', '-r', 'scan:=/scan']
    recorder = [sys.executable, str(Path(__file__).resolve()), '--record', str(out_csv)]
    player = ['ros2', 'bag', 'play', str(bag), '--clock', '--rate', str(rate), '--topics', *REPLAY_TOPICS]
    return {'cartographer': cartographer, 'recorder': recorder, 'player': player}


def _stop(process, wait=10.0):
    if process.poll() is None:
        os.killpg(process.pid, signal.SIGINT)
        try:
            process.wait(wait)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)


def run_bag(bag, out_csv, config_dir, basename, pbstream, rate, env, startup, settle):
    """Plays one bag through Cartographer and records ``/tracked_pose``. Returns the number of poses written."""
    cmds = commands(bag, config_dir, basename, out_csv, pbstream, rate)
    spawn = lambda argv: subprocess.Popen(argv, env=env, start_new_session=True)
    cartographer = spawn(cmds['cartographer'])
    recorder = spawn(cmds['recorder'])
    try:
        time.sleep(startup)  # Cartographer subscribes to /scan and looks up the lidar mounting only once it is up
        if cartographer.poll() is not None:
            raise RuntimeError('cartographer_node exited during start-up (is cartographer_ros sourced?)')
        subprocess.run(cmds['player'], env=env, check=True)
        time.sleep(settle)  # the last scans are still being matched
    finally:
        _stop(recorder)
        _stop(cartographer)
    return count_poses(out_csv)


# --- the pose recorder ----------------------------------------------------------------------------------------------

def yaw_of(q):
    return math.atan2(2.0 * (q.w * q.z + q.x * q.y), 1.0 - 2.0 * (q.y * q.y + q.z * q.z))


def pose_row(msg):
    """``(stamp, x, y, yaw)`` of a PoseStamped, the stamp in seconds."""
    return (msg.header.stamp.sec + msg.header.stamp.nanosec * 1e-9, msg.pose.position.x, msg.pose.position.y,
            yaw_of(msg.pose.orientation))


def format_row(row):
    return ','.join(f'{v:.6f}' for v in row)


def count_poses(path):
    path = Path(path)
    return sum(1 for _ in path.open()) if path.exists() else 0


def record(out_csv):
    """Writes every ``/tracked_pose`` to ``out_csv`` until interrupted. Runs as its own process (needs rclpy)."""
    import rclpy
    from geometry_msgs.msg import PoseStamped

    rclpy.init()
    node = rclpy.create_node('offline_slam_pose_recorder')
    with open(out_csv, 'w', buffering=1) as out:
        node.create_subscription(PoseStamped, POSE_TOPIC, lambda msg: out.write(format_row(pose_row(msg)) + '\n'), 100)
        try:
            rclpy.spin(node)
        except KeyboardInterrupt:
            pass
    node.destroy_node()
    if rclpy.ok():
        rclpy.shutdown()


# --- command line ---------------------------------------------------------------------------------------------------

def summarize_csv(path):
    """(poses, duration s, path length m) of a recorded pose file, or None if it has too few rows."""
    rows = [tuple(map(float, line.split(','))) for line in Path(path).read_text().splitlines() if line.strip()]
    if len(rows) < 2:
        return None
    length = sum(math.hypot(b[1] - a[1], b[2] - a[2]) for a, b in zip(rows, rows[1:]))
    return len(rows), rows[-1][0] - rows[0][0], length


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('bags', nargs='*', help='bag directories')
    ap.add_argument('--out-dir', default='sysid_poses')
    ap.add_argument('--racecar-version', default=os.environ.get('RACECAR_VERSION', 'NUC6'),
                    help='whose SLAM configuration to start from (default $RACECAR_VERSION)')
    ap.add_argument('--config-root', default=str(CONFIG_ROOT))
    ap.add_argument('--map', help='a .pbstream of the track: localize in it (pure localization) instead of mapping')
    ap.add_argument('--rate', type=float, default=1.0, help='bag playback rate; Cartographer must keep up with it')
    ap.add_argument('--startup', type=float, default=6.0, help='seconds to let Cartographer start before playing')
    ap.add_argument('--settle', type=float, default=3.0, help='seconds to keep recording after the bag ends')
    ap.add_argument('--domain-id', type=int, default=77)
    ap.add_argument('--rmw', default='rmw_fastrtps_cpp')
    ap.add_argument('--dry-run', action='store_true', help='print the commands and the derived configuration only')
    ap.add_argument('--record', metavar='CSV', help=argparse.SUPPRESS)  # internal: the recorder process
    args = ap.parse_args()

    if args.record:
        record(args.record)
        return
    bags = [b for b in args.bags if Path(b).is_dir()]  # a shell glob also matches the .metadata.yaml files
    if not bags:
        ap.error('no bag directories given')
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    env = environment(args.domain_id, args.rmw)
    with tempfile.TemporaryDirectory(prefix='offline_slam_') as work:
        config_dir, basename = derive_config(args.config_root, args.racecar_version, work, localization=bool(args.map))
        for bag in bags:
            out_csv = out_dir / (Path(bag).name + '.csv')
            if args.dry_run:
                cmds = commands(bag, config_dir, basename, out_csv, args.map, args.rate)
                print(f'# {Path(bag).name}')
                for name, argv in cmds.items():
                    print(f'  {name}: {" ".join(argv)}')
                print(f'  --- {basename} ---\n' + (config_dir / basename).read_text())
                continue
            print(f'{Path(bag).name}: running Cartographer ({"localization" if args.map else "mapping"}, '
                  f'rate {args.rate:g}) ...', flush=True)
            started = time.time()
            if run_bag(bag, out_csv, config_dir, basename, args.map, args.rate, env, args.startup, args.settle) == 0:
                sys.exit(f'{out_csv} is empty: no /tracked_pose arrived')
            summary = summarize_csv(out_csv)
            if summary is None:
                sys.exit(f'{out_csv} has too few poses')
            n, duration, length = summary
            print(f'  {n} poses over {duration:.0f} s, {length:.0f} m of path, wrote {out_csv} '
                  f'({time.time() - started:.0f} s)')


if __name__ == '__main__':
    main()
